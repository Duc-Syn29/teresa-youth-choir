import { readFile, writeFile } from 'node:fs/promises';
// Filter complete rules while preserving original cascade order, including media queries.
const source = await readFile(new URL('../css/style.css',import.meta.url),'utf8');
const home=/\.(?:hero(?:[\s.:#\[>{+-]|$)|hero-(?!year)|stats(?:[\s.:#\[>{+-]|$)|stat(?:[\s.:#\[>{+-]|$)|about-|timeline(?:[\s.:#\[>{+-]|$)|timeline-|journey-|contact-|activity-archive|memory-search|memory-result)/;
const year=/\.(?:year-(?!page|footer)|team-member|member-stat|member-note|leadership-|overview-|quote-card)/;
const event=/\.(?:activity-hero|activity-breadcrumb|activity-actions|activity-story|activity-photo|activity-gallery|activity-editorial|story-)/;
function blocks(text) {
  const result=[];let start=0,depth=0,quote='',comment=false;
  for(let i=0;i<text.length;i++) {
    const c=text[i],n=text[i+1];
    if(comment){if(c==='*'&&n==='/'){comment=false;i++;}continue;}
    if(quote){if(c==='\\')i++;else if(c===quote)quote='';continue;}
    if(c==='/'&&n==='*'){comment=true;i++;continue;}
    if(c==='"'||c==="'"){quote=c;continue;}
    if(c==='{')depth++;
    if(c==='}'&&--depth===0){result.push(text.slice(start,i+1));start=i+1;}
  }
  if(depth!==0)throw new Error('Unbalanced stylesheet');
  return result;
}
function filter(text,page) {
  return blocks(text).map(block=>{
    const open=block.indexOf('{'), head=block.slice(0,open).replace(/\/\*[\s\S]*?\*\//g,'').trim();
    if(/^@(media|supports|container|layer)\b/.test(head)){const body=filter(block.slice(open+1,-1),page);return body.trim()?`${block.slice(0,open+1)}${body}}`:'';}
    if(head.startsWith('@'))return block;
    const keep=head.split(',').some(selector=>{
      // Unknown and shared selectors remain. Only confidently exclusive rules are removed.
      if(home.test(selector))return page==='home';
      if(year.test(selector))return page==='archive';
      if(event.test(selector))return page==='archive';
      return true;
    });
    return keep?block:'';
  }).join('\n');
}
for(const page of ['home','archive','admin-base']) {
 const result=filter(source,page);
 await writeFile(new URL(`../css/${page}.css`,import.meta.url),`/* Generated by scripts/split-css.mjs; edit style.css. */\n${result}\n`);
 console.log(`${page}: ${Buffer.byteLength(result)} / ${Buffer.byteLength(source)} bytes`);
}
